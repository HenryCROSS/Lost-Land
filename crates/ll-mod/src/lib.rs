//! 迷途大陆的 mod 框架核心。
//!
//! 承接规格 §10「脚本层与 Mod 框架」的加载管线前半段：发现 → 解析清单
//! → 依赖拓扑排序。后续任务会在此基础上补齐内容注册表与 mod 集合
//! 双记录，本 crate 因此会持续增长。
//!
//! # 模块划分
//!
//! - [`discover`] / [`manifest`] / [`topo`] —— 加载管线的发现、解析、
//!   排序三个阶段。规格 §10.2 第四道防线（加载分阶段隔离）要求这三个
//!   阶段互相独立：一个 mod 的清单解析失败，不影响其他 mod 被发现和
//!   尝试解析。
//!
//! # 依赖方向
//!
//! 规格 §5：`ll-world` ← `ll-sim` ← `ll-script` ← `ll-mod`。本 crate
//! 是最上游的消费者，只依赖 `ll-core`，不得被下游任何 crate 反向依赖。

pub mod discover;
pub mod manifest;
pub mod topo;
