//! 迷途大陆的游戏内 UI。
//!
//! # P4：加载管理界面；P7 第一批：只读观测 HUD + 它需要的控件
//!
//! 规格 §5 把「游戏内 UI 控件库」记在 `ll-ui`，排期在 P7（[2026-08-18
//! 规格修订] 插入「物品与装备」新 P6 阶段后，原 P6 顺移为 P7）；但规格
//! §10.6 要求的加载管理界面（mod 管理器 + 脚本错误控制台）必须在 P4
//! 就出现——mod 框架本身就是 P4 的交付物，没有地方展示它的加载结果，
//! 等于 mod 框架交付了一半。工作区顶层裁定 P4-1 因此提前开了这个 crate
//! 名字，当时**范围严格限定**在文本 + 列表、按钮、滚动、错误面板
//! （[`load_report_view`]）。
//!
//! P7 第一批（只读观测界面：状态栏/角色面板/背包/装备栏）新增
//! [`hud`] 与它依赖的 [`widget`]——项目所有者裁定「不造完整通用控件库，
//! 但这四块屏幕真正需要的控件（面板/文本行/列表/条形/布局）必须做
//! 扎实，不能是临时画法」，见 [`widget`] 模块文档。
//!
//! **这一段此前写着「仍然排除：焦点导航、按钮、输入处理、设置界面/
//! 主菜单」——五项现在全部已落地，那句话是本仓库交接文档第五节第 9 条
//! 点名的两处文档腐烂之一，随本批次改正**：焦点导航（[`widget::focus`]）、
//! 按钮（[`widget::button`]）、输入处理（[`widget::hit_test`]/
//! [`widget::ui_mode`]）落在 P7 的 UI 交互层批次；游戏内菜单与设置界面
//! （[`screen`]）落在 P7 收尾批次。
//!
//! # 只做渲染，不做加载管线/世界模拟
//!
//! 加载管线本身（发现→解析→拓扑排序→加载脚本→注册）属于
//! `ll_mod::pipeline`——「一个数据/逻辑 crate 依赖渲染，会破坏规格 §5
//! 的依赖顺序」（裁定 P4-1 原文）。本 crate 只消费 `ll_mod` 产出的
//! `LoadReport`，把它变成屏幕上的文字；[`hud`] 同理，只读
//! `ll_world::entity::Agent`/`ll_world::state::WorldState::clock` 等
//! 已经算好的世界状态，不修改任何世界状态（任务书「本批次范围」一节
//! 明确排除的交互能力）。

pub mod hud;
pub mod load_report_view;
pub mod screen;
pub mod widget;

