//! # 本阶段（P4）只做加载管理界面
//!
//! 规格 §5 把「游戏内 UI 控件库」记在 `ll-ui`，排期在 P6；但规格 §10.6
//! 要求的加载管理界面（mod 管理器 + 脚本错误控制台）必须在 P4 就出现
//! ——mod 框架本身就是 P4 的交付物，没有地方展示它的加载结果，等于
//! mod 框架交付了一半。工作区顶层裁定 P4-1 因此提前开了这个 crate
//! 名字，但**范围严格限定**：文本 + 列表、按钮、滚动、错误面板。
//! 九宫格切片边框、焦点导航、完整像素 UI 控件库仍然留给 P6，不在这里
//! 造——本 crate 现在只有一个模块 [`load_report_view`]。
//!
//! # 只做渲染，不做加载管线
//!
