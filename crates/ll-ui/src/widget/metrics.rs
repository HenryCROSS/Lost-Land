//! 屏幕布局的**间距刻度**：三个常量，全项目共用。
//!
//! # 为什么这三个数住在 `widget/` 里
//!
//! 规格 §3.2 点名过这处：`widget/` 里**一个屏幕布局常量都没有**，全部
//! 住在两个互不知情的地方——
//!
//! - HUD 那一套：`hud::render::SCREEN_MARGIN` = 16、`PANEL_GAP` = 10、
//!   `hud::DEFAULT_PADDING` = 6；
//! - 模态屏那一套：`screen::SCREEN_PADDING` = 10、`SCREEN_SIDE_MARGIN` = 16。
//!
//! 两套之间没有任何共享的刻度，于是「模态屏的内边距」与「HUD 面板的
//! 内边距」是两个不相干的数（10 与 6），而「模态屏贴边留白」与「HUD
//! 贴边留白」是两个碰巧相等的数（16 与 16）——谁改了其中一个，另一个
//! 不会跟着动，也没有任何东西会红。
//!
//! `hud` 与 `screen` 都依赖 `widget`、彼此不依赖，因此 `widget` 是这三个
//! 数唯一能同时被两边看见的地方。规格 L3 要的「间距刻度统一成两档」在
//! 这里落地。
//!
//! # 两档，不是「只许出现这两个值」
//!
//! L3 的判据原文是「布局表达式里不再出现**未命名**的像素字面量（颜色
//! 分量与比例除外）」。**具名的第三个值仍然是允许的**，只要它说得出
//! 自己为什么不在刻度上——今天全项目只有一个：
//! `hud::placement::WORLD_MAP_CAPTION_MARGIN` = 8，它的文档写着「比
//! `SCREEN_MARGIN` 小：这行字贴在地图**内侧**，留白太大就会压到第一行
//! 格子上」。那是一条真实的约束，不是随手写的数。
//!
//! 组合也是允许的：`hud::placement::ACTION_MENU_TOP_MARGIN`
//! = `SCREEN_MARGIN + PANEL_GAP`（浮层比常驻面板再往下让一格）。它有
//! 名字，读得懂，且改刻度时自动跟上。

/// 面板与**窗口边缘**之间的留白（像素）。
///
/// 贴屏幕四边的那一档：状态栏贴左上、装备栏贴右上、底部两行贴下沿、
/// 模态屏面板的最小侧边留白，全部用它。
pub const SCREEN_MARGIN: f32 = 16.0;

/// 两块**相邻面板之间**的间隔（像素）。
///
/// 与 [`SCREEN_MARGIN`] 的分工：那个是「面板与屏幕」，这个是「面板与
/// 面板」。两条资源条之间、状态栏与角色面板之间、底部两行之间，全部
/// 用它。
pub const PANEL_GAP: f32 = 10.0;

/// 面板背景边框与它**自己的内容**之间的留白（像素）。
///
/// # 合并的是哪两个，为什么取 6
///
/// 规格 L3 要求把模态屏那套（`SCREEN_PADDING` = 10）与 HUD 那套
/// （`DEFAULT_PADDING` = 6）合并成一个，但**没说取哪个值**。取 6：
///
/// 1. 它只会让内容宽**变宽**（模态屏内容宽 500 → 508），而溢出门禁
///    （`crates/ll-ui/tests/i18n_text_width.rs`）的判据是行数预算——
///    内容变宽只会让行数变少或不变，**不可能让任何一条键新超预算**。
///    取 10 则会把六块 HUD 面板的内容宽各缩 8px，可能连带改动门禁判据，
///    那是把两件不相干的事绑在一起。
/// 2. HUD 有六块常驻面板加两行底栏用这个数，模态屏只有一块，取 6 动的
///    地方少。
pub const PANEL_PADDING: f32 = 6.0;
